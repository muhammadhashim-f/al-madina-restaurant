-- 1. Profiles
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Profiles viewable by user or admin" ON public.profiles
  FOR SELECT TO authenticated USING (id = auth.uid() OR public.is_admin());
CREATE POLICY "Profiles insert own profile" ON public.profiles
  FOR INSERT TO authenticated WITH CHECK (id = auth.uid() AND role = 'customer');
CREATE POLICY "Profiles update own profile or admin" ON public.profiles
  FOR UPDATE TO authenticated USING (id = auth.uid() OR public.is_admin())
  WITH CHECK ((id = auth.uid() AND role = 'customer') OR public.is_admin());

-- 2. Orders
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Orders customer insert" ON public.orders
  FOR INSERT TO anon, authenticated WITH CHECK (true);
CREATE POLICY "Orders select own or tracking or admin" ON public.orders
  FOR SELECT TO anon, authenticated
  USING ((auth.uid() IS NOT NULL AND user_id = auth.uid()) OR public.is_admin() OR (auth.uid() IS NULL));
CREATE POLICY "Orders admin update" ON public.orders
  FOR UPDATE TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin());
CREATE POLICY "Orders admin delete" ON public.orders
  FOR DELETE TO authenticated USING (public.is_admin());

